  id bigint generated by default as identity primary key,
  sender_name text not null,
  message text not null,
  gift_title text,
  value numeric,
  created_at timestamptz default now()
);
create index if not exists idx_cofre_guest_messages_created on public.cofre_guest_messages(created_at desc);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'cofre_guest_messages_limits') then
    alter table public.cofre_guest_messages add constraint cofre_guest_messages_limits check (
      char_length(sender_name) between 1 and 120
      and char_length(message) between 1 and 1000
      and coalesce(char_length(gift_title), 0) <= 200
      and (value is null or value between 0 and 100000)
    ) not valid;
  end if;
end;
$$;

-- ------------------------------------------------------------------------------
-- 4. POLÍTICAS DE RLS
-- ------------------------------------------------------------------------------
alter table public.casamento_config enable row level security;
alter table public.cofre_rsvp enable row level security;
alter table public.cofre_guest_messages enable row level security;

-- casamento_config: leitura pública, escrita só dos noivos
drop policy if exists "Leitura publica de casamento_config" on public.casamento_config;
create policy "Leitura publica de casamento_config" on public.casamento_config
  for select using (true);

drop policy if exists "Noivos atualizam casamento_config" on public.casamento_config;
create policy "Noivos atualizam casamento_config" on public.casamento_config
  for update to authenticated
  using (public.cofre_is_admin()) with check (public.cofre_is_admin());

-- cofre_rsvp: qualquer um confirma; só os noivos leem e excluem
drop policy if exists "Leitura publica de cofre_rsvp" on public.cofre_rsvp;   -- removida (expunha telefones)

drop policy if exists "Noivos leem cofre_rsvp" on public.cofre_rsvp;
create policy "Noivos leem cofre_rsvp" on public.cofre_rsvp
  for select to authenticated using (public.cofre_is_admin());

drop policy if exists "Insercao publica de cofre_rsvp" on public.cofre_rsvp;
create policy "Insercao publica de cofre_rsvp" on public.cofre_rsvp
  for insert with check (true);

drop policy if exists "Noivos excluem cofre_rsvp" on public.cofre_rsvp;
create policy "Noivos excluem cofre_rsvp" on public.cofre_rsvp
  for delete to authenticated using (public.cofre_is_admin());

-- cofre_guest_messages: leitura e envio públicos; noivos podem moderar (excluir)
drop policy if exists "Leitura publica de mensagens" on public.cofre_guest_messages;
create policy "Leitura publica de mensagens" on public.cofre_guest_messages
  for select using (true);

drop policy if exists "Convidados podem enviar mensagens" on public.cofre_guest_messages;
create policy "Convidados podem enviar mensagens" on public.cofre_guest_messages
  for insert with check (true);

drop policy if exists "Noivos excluem mensagens" on public.cofre_guest_messages;
create policy "Noivos excluem mensagens" on public.cofre_guest_messages
  for delete to authenticated using (public.cofre_is_admin());

-- ------------------------------------------------------------------------------
-- 5. STORAGE: bucket público para as fotos enviadas pelo painel
-- ------------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('cofre-imagens', 'cofre-imagens', true, 5242880,
        array['image/jpeg', 'image/png', 'image/webp', 'image/gif'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Noivos enviam imagens" on storage.objects;
create policy "Noivos enviam imagens" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'cofre-imagens' and public.cofre_is_admin());

drop policy if exists "Noivos atualizam imagens" on storage.objects;
create policy "Noivos atualizam imagens" on storage.objects
  for update to authenticated
  using (bucket_id = 'cofre-imagens' and public.cofre_is_admin());

drop policy if exists "Noivos excluem imagens" on storage.objects;
create policy "Noivos excluem imagens" on storage.objects
  for delete to authenticated
  using (bucket_id = 'cofre-imagens' and public.cofre_is_admin());

