-- ------------------------------------------------------------------------------
create table if not exists public.cofre_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  created_at timestamptz default now()
);
alter table public.cofre_admins enable row level security;
-- Sem políticas: ninguém lê/escreve esta tabela pela API. Só via SQL Editor.

create or replace function public.cofre_is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.cofre_admins where user_id = auth.uid());
$$;
revoke all on function public.cofre_is_admin() from public;
grant execute on function public.cofre_is_admin() to anon, authenticated;

