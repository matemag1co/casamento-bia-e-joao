-- 2. TABELA DE LANÇAMENTOS DO COFRE (Envelopes e Valores Livres)
create table if not exists public.cofre_entries (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('env', 'liv')),
  value numeric not null,
  env_id text,
  note text,
  created_at timestamptz default now()
);

-- Índice para busca rápida de envelopes marcados
create index if not exists idx_cofre_entries_env_id on public.cofre_entries(env_id) where env_id is not null;
create index if not exists idx_cofre_entries_created on public.cofre_entries(created_at asc);

-- 3. TABELA DE RECADOS DOS PADRINHOS & CONVIDADOS (Mural dos Noivos)
create table if not exists public.cofre_guest_messages (
  id bigint generated by default as identity primary key,
  sender_name text not null,
  message text not null,
  gift_title text,
  value numeric,
  created_at timestamptz default now()
);

create index if not exists idx_cofre_guest_messages_created on public.cofre_guest_messages(created_at desc);

