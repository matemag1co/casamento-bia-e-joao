-- ==============================================================================
-- 6. POLÍTICAS DE SEGURANÇA (Row Level Security - RLS)
-- ==============================================================================
alter table public.cofre_config enable row level security;
alter table public.cofre_rsvp enable row level security;
alter table public.cofre_guest_messages enable row level security;
alter table public.cofre_entries enable row level security;

-- cofre_config: Leitura pública, edição pelos noivos
drop policy if exists "Leitura publica de cofre_config" on public.cofre_config;
create policy "Leitura publica de cofre_config" on public.cofre_config for select using (true);

drop policy if exists "Edicao de cofre_config para noivos" on public.cofre_config;
create policy "Edicao de cofre_config para noivos" on public.cofre_config for update using (public.is_cofre_writer());

-- cofre_rsvp: Leitura pública (para exibir contagem e lista), inserção aberta para convidados
drop policy if exists "Leitura publica de cofre_rsvp" on public.cofre_rsvp;
create policy "Leitura publica de cofre_rsvp" on public.cofre_rsvp for select using (true);

drop policy if exists "Insercao publica de cofre_rsvp" on public.cofre_rsvp;
create policy "Insercao publica de cofre_rsvp" on public.cofre_rsvp for insert with check (true);

drop policy if exists "Noivos podem moderar cofre_rsvp" on public.cofre_rsvp;
create policy "Noivos podem moderar cofre_rsvp" on public.cofre_rsvp for delete using (public.is_cofre_writer());

drop policy if exists "Noivos podem atualizar cofre_rsvp" on public.cofre_rsvp;
create policy "Noivos podem atualizar cofre_rsvp" on public.cofre_rsvp for update using (public.is_cofre_writer());

-- cofre_guest_messages: Leitura pública, envio público
drop policy if exists "Leitura publica de mensagens" on public.cofre_guest_messages;
create policy "Leitura publica de mensagens" on public.cofre_guest_messages for select using (true);

drop policy if exists "Convidados podem enviar mensagens" on public.cofre_guest_messages;
create policy "Convidados podem enviar mensagens" on public.cofre_guest_messages for insert with check (true);

drop policy if exists "Noivos podem moderar mensagens" on public.cofre_guest_messages;
create policy "Noivos podem moderar mensagens" on public.cofre_guest_messages for delete using (public.is_cofre_writer());

-- cofre_entries: Leitura pública, escrita pelos noivos
drop policy if exists "Leitura publica de cofre_entries" on public.cofre_entries;
create policy "Leitura publica de cofre_entries" on public.cofre_entries for select using (true);

drop policy if exists "Inserir cofre_entries para noivos" on public.cofre_entries;
create policy "Inserir cofre_entries para noivos" on public.cofre_entries for insert with check (public.is_cofre_writer());

drop policy if exists "Deletar cofre_entries para noivos" on public.cofre_entries;
create policy "Deletar cofre_entries para noivos" on public.cofre_entries for delete using (public.is_cofre_writer());

-- ==============================================================================
-- 7. HABILITAR SINCRONIZAÇÃO EM TEMPO REAL (Realtime)
-- ==============================================================================
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'cofre_rsvp') then
    alter publication supabase_realtime add table public.cofre_rsvp;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'cofre_guest_messages') then
    alter publication supabase_realtime add table public.cofre_guest_messages;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'cofre_config') then
    alter publication supabase_realtime add table public.cofre_config;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'cofre_entries') then
    alter publication supabase_realtime add table public.cofre_entries;
  end if;
end;
$$;
