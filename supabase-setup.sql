-- ------------------------------------------------------------------------------
-- 2. CONFIRMAÇÃO DE PRESENÇA (RSVP INDIVIDUAL)
-- ------------------------------------------------------------------------------
create table if not exists public.cofre_rsvp (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  status text not null default 'confirmed', -- 'confirmed' ou 'declined'
  guests_count int not null default 1,
  guests_names text,
  message text,
  sent_to text, -- 'joao', 'bia', 'site'
  created_at timestamptz default now()
);
create index if not exists idx_cofre_rsvp_created on public.cofre_rsvp(created_at desc);

-- Limites básicos contra spam/abuso (NOT VALID = não reprova linhas antigas)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'cofre_rsvp_limits') then
    alter table public.cofre_rsvp add constraint cofre_rsvp_limits check (
      char_length(name) between 1 and 150
      and char_length(phone) between 1 and 40
      and status in ('confirmed', 'declined')
      and guests_count between 0 and 10
      and coalesce(char_length(message), 0) <= 1000
      and coalesce(char_length(guests_names), 0) <= 500
      and coalesce(char_length(sent_to), 0) <= 20
    ) not valid;
  end if;
end;
$$;

-- Contagem pública (sem expor nomes/telefones)
create or replace function public.cofre_rsvp_stats()
returns table (confirmed bigint, declined bigint, total bigint)
language sql stable security definer
set search_path = public
as $$
  select
    count(*) filter (where status = 'confirmed'),
    count(*) filter (where status <> 'confirmed'),
    count(*)
  from public.cofre_rsvp;
$$;
revoke all on function public.cofre_rsvp_stats() from public;
grant execute on function public.cofre_rsvp_stats() to anon, authenticated;

